<?php

declare(strict_types=1);

namespace App\Modules\IdentityAccess\Permissions;

/** Renders docs/architecture/PERMISSION_MATRIX.md from the catalogue so the document can never drift from the code. */
final class PermissionMatrixDocument
{
    public static function render(): string
    {
        $roles = PermissionCatalogue::roleNames();
        $out = "# Permission Matrix\n\n";
        $out .= "> Generated by `php artisan rbac:matrix` from `PermissionCatalogue`. **Do not edit by hand**; a test fails when this file is stale.\n\n";
        $out .= 'Default grants for the seeded roles. Roles are created once; administrators may later edit them (the seeder never overwrites edits). ';
        $out .= "**Super Admin** holds every permission through an explicit, audited bypass. `⚠` marks sensitive permissions whose use is audited even for Super Admin.\n\n";
        $out .= '| Permission | '.implode(' | ', $roles)." |\n";
        $out .= '|---|'.str_repeat(':---:|', count($roles))."\n";

        $defaults = [];
        foreach ($roles as $role) {
            $defaults[$role] = PermissionCatalogue::defaultsFor($role);
        }

        foreach (PermissionCatalogue::permissions() as $permission) {
            $flag = PermissionCatalogue::isSensitive($permission) ? ' ⚠' : '';
            $cells = array_map(fn (string $role) => in_array($permission, $defaults[$role], true) ? '✔' : '', $roles);
            $out .= "| `{$permission}`{$flag} | ".implode(' | ', $cells)." |\n";
        }

        $out .= "\n## Rules enforced in code\n\n";
        $out .= "- A staff member can only grant roles/permissions they hold themselves; only a Super Admin can assign Super Admin.\n";
        $out .= "- The last active Super Admin cannot be demoted, disabled or have the role removed.\n";
        $out .= "- Super Admin's permissions cannot be edited; system roles cannot be deleted; roles still assigned cannot be deleted.\n";
        $out .= "- Unknown permission names fail closed (access denied / ignored when saving a role).\n";
        $out .= "- Every `/admin` route requires `auth:admin` + `permission:*` unless listed in `tests/Architecture/RouteAuthorizationTest.php`.\n";

        return $out;
    }
}
